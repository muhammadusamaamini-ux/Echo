// The safe bridge between Echo's screens and the main process.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch) => (fn) => ipcRenderer.on(ch, (e, ...a) => fn(...a));

contextBridge.exposeInMainWorld('echo', {
  loadLibrary: call('lib:load'),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch (e) { return f.path || ''; } },
  saveLibrary: call('lib:save'),
  pendingFiles: call('app:pendingFiles'),
  info: call('app:info'),
  open: call('dialog:open'),
  saveDialog: call('dialog:save'),
  fileUrl: call('file:url'),
  exists: call('file:exists'),
  isDir: call('file:isDir'),
  writeTemp: call('file:writeTemp'),
  writeData: call('file:writeData'),
  readText: call('file:readText'),
  deleteFile: call('file:delete'),
  showInFolder: call('shell:show'),
  openExternal: call('shell:open'),
  openPath: call('shell:openPath'),
  fullscreen: call('win:fullscreen'),
  scanMusic: call('scan:music'),
  scanVideos: call('scan:videos'),
  tags: call('meta:tags'),
  art: call('meta:art'),
  driveRead: call('drive:read'),
  oembed: call('yt:oembed'),
  probe: call('ff:probe'),
  thumb: call('ff:thumb'),
  waveform: call('ff:waveform'),
  frame: call('ff:frame'),
  outSize: call('ff:outSize'),
  ffExport: call('ff:export'),
  ffCancel: call('ff:cancel'),
  hashFile: call('sync:hash'),
  fileSize: call('sync:size'),
  syncUpload: call('sync:upload'),
  syncDownload: call('sync:download'),
  syncMusicDir: call('sync:musicDir'),
  checkUpdate: call('upd:check'),
  downloadUpdate: call('upd:download'),
  installUpdate: call('upd:install'),
  onOpenFiles: on('open-files'),
  onFullscreen: on('fullscreen'),
  onYtProgress: on('yt:progress'),
  onFfProgress: on('ff:progress'),
  onUpdateAvailable: on('upd:available'),
  onUpdateProgress: on('upd:progress'),
  onUpdateDownloaded: on('upd:downloaded'),
  onUpdateError: on('upd:error'),
});
